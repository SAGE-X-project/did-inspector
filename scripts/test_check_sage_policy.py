import copy
import json
import os
import unittest
from pathlib import Path
import check_sage_policy as checker


class InstantTests(unittest.TestCase):
    def test_offsets_and_nanosecond_boundary(self):
        self.assertEqual(checker.instant("2030-01-01T09:00:00.5+09:00"), checker.instant("2030-01-01T00:00:00.5Z"))
        self.assertEqual(checker.instant("2030-01-01T00:00:00,5Z"), checker.instant("2030-01-01T00:00:00.5Z"))
        self.assertNotEqual(checker.instant("2030-01-01T00:00:00.499999999Z"), checker.instant("2030-01-01T00:00:00.5Z"))
        with self.assertRaises(AssertionError):
            checker.instant("2030-01-01")


@unittest.skipUnless(os.environ.get("SAGE_BATCH_REPORT_DIR"), "actual reports are generated by adapter CI")
class PolicyEvidenceTests(unittest.TestCase):
    def setUp(self):
        root = Path(os.environ["SAGE_BATCH_REPORT_DIR"])
        self.raw = json.loads((root / "resolution-did-1.1-raw.json").read_text())
        self.report = json.loads((root / "resolution-did-1.1.json").read_text())

    def test_actual_policy(self):
        self.assertEqual(len(checker.verify_policy(self.raw, self.report)), 8)

    def test_capture_mutations_do_not_pass(self):
        changes = [lambda x: x.update(role="SAGE authority"), lambda x: x.update(capture_error="lost"),
                   lambda x: x.update(clock_values=[]), lambda x: x.update(clock_values=["2029-01-01T00:00:00Z"]),
                   lambda x: x["consumer"].update(input="e30="), lambda x: x["consumer"].update(version="1.0"),
                   lambda x: x["methods"][0]["revoked"].update(kind="string"),
                   lambda x: x["retrieval"].update(operation="invented RP"), lambda x: x["retrieval"].update(error=""),
                   lambda x: x["retrieval"]["calls"][0].update(input="did:example:other"),
                   lambda x: x["retrieval"]["calls"][0].update(options="bnVsbA=="),
                   lambda x: x["retrieval"]["calls"][0]["result"].update(returned_id="other")]
        for change in changes:
            raw = copy.deepcopy(self.raw)
            case = next(c for c in raw["cases"] if c["case"].endswith("/key-policy-revoked-utc-1"))
            values = json.loads(case["observations"][0]["observed"])
            change(values[0])
            case["observations"][0]["observed"] = json.dumps(values)
            with self.assertRaises((AssertionError, KeyError, ValueError, TypeError)):
                checker.verify_policy(raw, self.report)

    def test_hidden_failure_wrong_case_and_lost_findings_do_not_pass(self):
        for field, value in [("verdict", "PASS"), ("statement", "other")]:
            raw = copy.deepcopy(self.raw)
            case = next(c for c in raw["cases"] if "/key-policy-format-" in c["case"])
            case["observations"][0][field] = value
            with self.assertRaises(AssertionError):
                checker.verify_policy(raw, self.report)
        raw = copy.deepcopy(self.raw)
        case = next(c for c in raw["cases"] if "/key-policy-format-" in c["case"])
        f = json.loads(case["observations"][0]["input"])
        f["vectors"][12]["valid"] = True
        for o in case["observations"]:
            o["input"] = json.dumps(f)
        with self.assertRaises(AssertionError):
            checker.verify_policy(raw, self.report)
        for ident in ["cid10#conformance.2", "cid10#fragment-resolution.4"]:
            report = copy.deepcopy(self.report)
            next(s for s in report["statements"] if s["id"] == ident)["verdict"] = "PASS"
            with self.assertRaises(AssertionError):
                checker.verify_policy(self.raw, report)
