import copy
import json
import os
from pathlib import Path
import unittest
import check_sage_choices as checker

class PublicOracleTests(unittest.TestCase):
    def test_public_vectors_and_local_scope(self):
        for (name,secret),(_,length) in checker.CODECS.items():
            values=checker.keys(name,secret)
            self.assertEqual(len(values),2)
            self.assertTrue(all(len(x)==length for x in values))
        checker.owned('https://127.0.0.1:443/1.0/identifiers/')
        for endpoint in ['https://external.example/1.0/identifiers/','http://127.0.0.1:443/1.0/identifiers/','https://127.0.0.1:443/other','https://user@127.0.0.1:443/1.0/identifiers/']:
            with self.assertRaises(AssertionError):checker.owned(endpoint)

    def test_certificate_ip_names_are_exact(self):
        import ipaddress
        parsed=checker.certificate_ips('    X509v3 extensions:\n        X509v3 Subject Alternative Name:\n            IP Address:127.0.0.10, IP Address:0:0:0:0:0:0:0:1\n    Signature Algorithm: example')
        self.assertNotIn(ipaddress.ip_address('127.0.0.1'),parsed)
        self.assertIn(ipaddress.ip_address('127.0.0.10'),parsed)
        self.assertIn(ipaddress.ip_address('::1'),parsed)

    def test_common_name_and_other_extensions_are_not_san(self):
        cn='    Subject: CN = IP Address:127.0.0.1\n'
        self.assertEqual(checker.certificate_ips(cn),set())
        unrelated=cn+'    X509v3 extensions:\n        X509v3 Authority Key Identifier:\n            IP Address:127.0.0.1\n    Signature Algorithm: example'
        self.assertEqual(checker.certificate_ips(unrelated),set())
        wrong_san=cn+'    X509v3 extensions:\n        X509v3 Subject Alternative Name:\n            IP Address:127.0.0.10\n    Signature Algorithm: example'
        import ipaddress
        self.assertNotIn(ipaddress.ip_address('127.0.0.1'),checker.certificate_ips(wrong_san))

@unittest.skipUnless(os.environ.get('SAGE_BATCH_REPORT_DIR'),'actual reports generated by adapter CI')
class ActualChoiceTests(unittest.TestCase):
    def setUp(self):
        p=Path(os.environ['SAGE_BATCH_REPORT_DIR'])
        self.raw=json.loads((p/'resolution-did-1.1-raw.json').read_text());self.report=json.loads((p/'resolution-did-1.1.json').read_text())
    def test_complete_actual_evidence(self):self.assertEqual(len(checker.verify_choices(self.raw,self.report)),8)
    def mutate(self,suffix,change,reject=True):
        raw=copy.deepcopy(self.raw);c=next(c for c in raw['cases'] if c['case'].endswith('/choice-'+suffix))
        value=json.loads(c['observations'][0]['observed']);change(value)
        for o in c['observations']:o['observed']=json.dumps(value)
        if reject:
            with self.assertRaises((AssertionError,KeyError,ValueError,TypeError)):checker.verify_choices(raw,self.report)
        else:self.assertEqual(len(checker.verify_choices(raw,self.report)),8)
    def test_missing_and_changed_actual_values(self):
        for name,change in [
            ('codec-Ed25519-public',lambda v:v[0].update(encoded='zwrong')),
            ('codec-Ed25519-public',lambda v:v[0].update(decoded='AA==')),
            ('proxy-post-false',lambda v:v['native'][0].update(input='did:example:other')),
            ('proxy-post-true',lambda v:v['wire'][0].update(method='GET')),
            ('ip-certificate',lambda v:v[0].update(server_verified=False)),
            ('ip-certificate',lambda v:v[0].update(server_peer=None)),
            ('key-conversion-Ed25519',lambda v:v[0].update(after='zchanged')),
            ('key-conversion-P-256',lambda v:v[0].update(convert_error='refused')),
            ('optional-public-multibase-local-model',lambda v:v['variants'][1].update(model='e30=')),
        ]:
            with self.subTest(name=name):self.mutate(name,change)
    def test_unrelated_diagnostics_do_not_change_equivalence(self):
        self.mutate('codec-Ed25519-public',lambda v:v[2].update(decode_error='different error shape',decode_name='diagnostic'),False)
        self.mutate('ip-certificate',lambda v:v[0].update(client_verified=False),False)
        self.mutate('key-conversion-Ed25519',lambda v:v[0].update(after_type='other internal representation',after_raw='AA=='),False)
    def test_codec_role_or_name_cannot_be_reassigned(self):
        raw=copy.deepcopy(self.raw)
        secret=next(c for c in raw['cases'] if c['case'].endswith('/choice-codec-Ed25519-public-test-secret'))
        public=next(c for c in raw['cases'] if c['case'].endswith('/choice-codec-Ed25519-public'))
        secret['observations']=copy.deepcopy(public['observations'])
        with self.assertRaises(AssertionError):checker.verify_choices(raw,self.report)

    def test_dropped_or_duplicate_cases(self):
        for duplicate in [False,True]:
            raw=copy.deepcopy(self.raw);c=next(c for c in raw['cases'] if '/choice-codec-' in c['case'])
            if duplicate:raw['cases'].append(copy.deepcopy(c))
            else:raw['cases'].remove(c)
            with self.assertRaises(AssertionError):checker.verify_choices(raw,self.report)
