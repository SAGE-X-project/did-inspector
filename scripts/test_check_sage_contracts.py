import copy
import json
import os
import unittest
from pathlib import Path

import check_sage_contracts as checker


@unittest.skipUnless(os.environ.get("SAGE_BATCH_REPORT_DIR"), "actual reports are generated by adapter CI")
class ContractEvidenceTests(unittest.TestCase):
    def setUp(self):
        root = Path(os.environ["SAGE_BATCH_REPORT_DIR"])
        self.raw = json.loads((root / "resolution-did-1.1-raw.json").read_text())
        self.report = json.loads((root / "resolution-did-1.1.json").read_text())

    def test_actual_contracts(self):
        self.assertEqual(len(checker.verify_contracts(self.raw, self.report)), 23)

    def test_changed_capture_does_not_pass(self):
        changes = [lambda x: x.update(operation="invented entry"),
                   lambda x: x.update(identifier="bnVsbA=="),
                   lambda x: x.update(options="bnVsbA=="),
                   lambda x: x.update(capture_error="lost"),
                   lambda x: x["metadata"]["resolution"].update(serializer="invented serializer"),
                   lambda x: x["metadata"]["document"].update(bytes="e30="),
                   lambda x: x["result"].update(has_content=False),
                   lambda x: x["reference"].update(content_metadata={"changed": True}),
                   lambda x: x["reference"]["snapshot"].update(id="other")]
        for change in changes:
            raw = copy.deepcopy(self.raw)
            c = next(c for c in raw["cases"] if "/native-contract-document-0-false" in c["case"])
            out = json.loads(c["observations"][0]["observed"])
            change(out)
            for o in c["observations"]:
                o["observed"] = json.dumps(out)
            with self.assertRaises((AssertionError, ValueError, KeyError, TypeError)):
                checker.verify_contracts(raw, self.report)

    def test_lost_or_relabelled_cases_do_not_pass(self):
        for field, value in [("statement", "other"), ("verdict", "FAIL"), ("input", "{}"), ("observed", "{}")]:
            raw = copy.deepcopy(self.raw)
            c = next(c for c in raw["cases"] if "/native-contract-" in c["case"])
            c["observations"][0][field] = value
            with self.assertRaises((AssertionError, ValueError, KeyError, TypeError)):
                checker.verify_contracts(raw, self.report)
        raw = copy.deepcopy(self.raw)
        raw["cases"] = [c for c in raw["cases"] if "native-contract-zero-dereference" not in c["case"]]
        with self.assertRaises(AssertionError):
            checker.verify_contracts(raw, self.report)


class SemanticEqualityTests(unittest.TestCase):
    def test_known_sets_and_ordered_extensions(self):
        same = checker.semantic_equal
        self.assertTrue(same({"id": "x", "controller": ["a", "b"]}, {"controller": ["b", "a"], "id": "x"}, "document"))
        self.assertTrue(same({"controller": "a"}, {"controller": ["a"]}, "document"))
        self.assertTrue(same({"service": [{"type": "a", "serviceEndpoint": ["a", "b"]}]}, {"service": [{"type": ["a"], "serviceEndpoint": ["b", "a"]}]}, "document"))
        self.assertTrue(same({"proof": ["a", "b"]}, {"proof": ["b", "a"]}, "metadata"))
        self.assertFalse(same({"extra": ["a", "b"]}, {"extra": ["b", "a"]}, "document"))
        for left, right, kind in [(["a", "a"], ["a", "b"], "set"), (["a"], ["a", "b"], "set"), ("a", ["a"], "set"), ({"id": "x"}, {"id": "y"}, "document"), ({"id": "x"}, {}, "document"), (True, 1, "unknown"), ([True], [1], "unknown"), ([[True]], [[1]], "unknown"), ([{"extra": [True]}], [{"extra": [1]}], "unknown")]:
            self.assertFalse(same(left, right, kind))
