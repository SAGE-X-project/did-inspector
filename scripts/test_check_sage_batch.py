import copy
import json
import os
import shutil
import tempfile
import unittest
from pathlib import Path

import check_sage_batch as checker


class ReviewTests(unittest.TestCase):
    def test_complete_frozen_review(self):
        self.assertEqual(len(checker.verify_review()), 353)

    def test_review_rejects_loss_duplicates_and_changed_provenance(self):
        with tempfile.TemporaryDirectory() as directory:
            repo = Path(directory)
            for name in ["docs", "statements", "profiles/sageresolution"]:
                (repo / name).mkdir(parents=True)
            for name in ["docs/sage-resolution-batch-review.json", "docs/sage-resolution-gaps.json",
                         "statements/cid10.json", "statements/did11-cr20260305.json", "statements/res10-crd20261001.json",
                         "profiles/sageresolution/did-v1.1-context.jsonld"]:
                shutil.copyfile(checker.REPO / name, repo / name)
            target = repo / "docs/sage-resolution-batch-review.json"
            original = json.loads(target.read_text())
            changes = [lambda x: x["clauses"].pop(),
                       lambda x: x["clauses"].append(copy.deepcopy(x["clauses"][0])),
                       lambda x: x["anchor"].update(inspector_revision="different"),
                       lambda x: x["clauses"][0].update(status="PASS"),
                       lambda x: x["clauses"][0].update(text="changed"),
                       lambda x: x["clauses"][0].update(text_sha256="0" * 64),
                       lambda x: x["clauses"][0].update(historical_route="different"),
                       lambda x: x["clauses"][0].update(level="recommendation"),
                       lambda x: x["groups"].update(unknown=1)]
            for change in changes:
                value = copy.deepcopy(original)
                change(value)
                target.write_text(json.dumps(value))
                with self.assertRaises(AssertionError):
                    checker.verify_review(repo)
            target.write_text(json.dumps(original))
            self.assertEqual(len(checker.verify_review(repo)), 353)
            (repo / "profiles/sageresolution/did-v1.1-context.jsonld").write_bytes(b"{}")
            with self.assertRaises(AssertionError):
                checker.verify_review(repo)

    def test_independent_base58_leading_zero_controls(self):
        for data, value in [(b"", "z"), (b"\0", "z1"), (b"\0\0\1", "z112"), (bytes([58]), "z21"), (bytes([255]), "z5Q")]:
            self.assertEqual(checker.btc(data), value)


@unittest.skipUnless(os.environ.get("SAGE_BATCH_REPORT_DIR"), "actual reports are generated by the adapter CI job")
class EvidenceTests(unittest.TestCase):
    def setUp(self):
        root = Path(os.environ["SAGE_BATCH_REPORT_DIR"])
        self.raw = json.loads((root / "resolution-did-1.1-raw.json").read_text())
        self.report = json.loads((root / "resolution-did-1.1.json").read_text())

    def test_actual_report(self):
        self.assertEqual(len(checker.verify_batch(self.raw, self.report)), 61)

    def test_report_evidence_mutations_are_rejected(self):
        for group, field, change in [
                ("syntax", "operation", "invented parser"),
                ("syntax", "value", "wrong reference"),
                ("codec", "encoded", "zincorrect"),
                ("codec", "decode_secret", True),
                ("client", "server_calls", 0),
                ("client", "server_tls", False),
                ("client", "server_role", "different server"),
                ("client", "native", []),
                ("retrieval", "clock", 0),
                ("retrieval", "reference", "different"),
                ("document", "positive", {}),
                ("context", "data", "e30="),
        ]:
            raw = copy.deepcopy(self.raw)
            case = next(c for c in raw["cases"] if f"/library-{group}-" in c["case"])
            out = json.loads(case["observations"][0]["observed"])
            if group in ["syntax", "codec"]:
                out[0][field] = change
            else:
                out[field] = change
            for obs in case["observations"]:
                obs["observed"] = json.dumps(out)
            with self.assertRaises((AssertionError, ValueError, KeyError, TypeError)):
                checker.verify_batch(raw, self.report)
        raw = copy.deepcopy(self.raw)
        case = next(c for c in raw["cases"] if "/library-context-producer-" in c["case"])
        case["observations"][0]["verdict"] = "PASS"
        with self.assertRaises(AssertionError):
            checker.verify_batch(raw, self.report)
        raw = copy.deepcopy(self.raw)
        case = next(c for c in raw["cases"] if "/library-client-" in c["case"])
        case["observations"][0]["input"] = ""
        with self.assertRaises(AssertionError):
            checker.verify_batch(raw, self.report)
        raw = copy.deepcopy(self.raw)
        raw["cases"] = [c for c in raw["cases"] if "/library-syntax-" not in c["case"]]
        with self.assertRaises(AssertionError):
            checker.verify_batch(raw, self.report)


if __name__ == "__main__":
    unittest.main()
