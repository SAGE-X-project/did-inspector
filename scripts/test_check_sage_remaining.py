import copy
import json
import os
import tempfile
import unittest
from pathlib import Path
import check_sage_remaining as checker


class UtilityTests(unittest.TestCase):
    def test_owned_endpoint_and_typed_literals(self):
        checker.owned('https://127.0.0.1:1234/')
        checker.owned('https://[::1]:1234/')
        for endpoint in ['http://127.0.0.1:1234/', 'https://external.example/', 'https://user@127.0.0.1:1/', 'https://127.0.0.1/', 'https://127.0.0.1:1/#fragment']:
            with self.assertRaises(AssertionError):
                checker.owned(endpoint)
        for value, expected in [({'kind': 'string', 'text': 'literal'}, 'literal'), ({'kind': 'integer', 'text': '-42'}, -42), ({'kind': 'double', 'text': '2'}, 2.0), ({'kind': 'boolean'}, False), ({'kind': 'null'}, None), ({'kind': 'list'}, []), ({'kind': 'map'}, {})]:
            self.assertEqual(checker.typed_json(value), expected)
        with self.assertRaises(AssertionError):
            checker.typed_json({'kind': 'unknown'})


@unittest.skipUnless(os.environ.get('SAGE_BATCH_REPORT_DIR'), 'actual reports are generated by adapter CI')
class GroupedEvidenceTests(unittest.TestCase):
    def setUp(self):
        root = Path(os.environ['SAGE_BATCH_REPORT_DIR'])
        self.raw = json.loads((root / 'resolution-did-1.1-raw.json').read_text())
        self.report = json.loads((root / 'resolution-did-1.1.json').read_text())

    def test_all_grouped_evidence(self):
        self.assertEqual(len(checker.verify_remaining(self.raw, self.report)), 77)

    def mutate(self, suffix, change):
        raw = copy.deepcopy(self.raw)
        case = next(c for c in raw['cases'] if c['case'].endswith('/remaining-' + suffix))
        values = json.loads(case['observations'][0]['observed'])
        change(values)
        for observation in case['observations']:
            observation['observed'] = json.dumps(values)
        with self.assertRaises((AssertionError, KeyError, ValueError, TypeError)):
            checker.verify_remaining(raw, self.report)

    def test_missing_mismatched_or_hidden_operation_evidence(self):
        for suffix, change in [
            ('value-created', lambda v: v[0].update(reader='invented reader')),
            ('value-created', lambda v: v[0]['request'].update(input='e30=')),
            ('fields-public-jwk', lambda v: v['control'].update(input='e30=')),
            ('fields-secret-jwk-shape', lambda v: v['negative'].update(error='')),
            ('fields-substructures', lambda v: v['calls'][0].update(version='1.0')),
            ('routing-forward-uri-options', lambda v: v.update(resolve_options=['e30='])),
            ('routing-service-id', lambda v: v.update(role='SAGE operational source')),
            ('routing-service-urls', lambda v: v['result'].update(raw='W10=')),
            ('native-keys', lambda v: v.update(returned_id='other')),
            ('trust-mutual-tls', lambda v: v[0].update(client_verified=False)),
            ('trust-mutual-tls', lambda v: v[0].update(server_peer=None)),
            ('operation-cache-refusal', lambda v: v[1].update(calls=2)),
            ('operation-parameters-time', lambda v: v[0].update(version_time='other')),
            ('binding-uri-list-GET', lambda v: v['exchange'].update(status=200)),
            ('binding-uri-list-POST', lambda v: v['exchange']['header'].update(Location=['https://external.example/'])),
            ('expansion-output', lambda v: v[1].update(data_model='e30=')),
            ('proxy-metadata', lambda v: v['result']['content_metadata'].update(deactivated=False)),
            ('preference-resolve', lambda v: v[1]['metadata'].update(contentType='text/plain')),
            ('cid-http-GET', lambda v: v[1]['exchange'].update(body='e30=')),
            ('minimal-representation', lambda v: v['Converted']['calls'][0].update(media_type='application/did')),
        ]:
            with self.subTest(suffix=suffix):
                self.mutate(suffix, change)

    def test_case_loss_duplicates_and_hidden_failure(self):
        for change in [lambda r: r['cases'].pop(), lambda r: r['cases'].append(copy.deepcopy(r['cases'][-1]))]:
            raw = copy.deepcopy(self.raw)
            change(raw)
            with self.assertRaises(AssertionError):
                checker.verify_remaining(raw, self.report)
        raw = copy.deepcopy(self.raw)
        case = next(c for c in raw['cases'] if c['case'].endswith('/remaining-native-keys'))
        next(o for o in case['observations'] if o['statement'] == checker.KID)['verdict'] = 'PASS'
        with self.assertRaises(AssertionError):
            checker.verify_remaining(raw, self.report)

    def test_all_anchor_rows_and_followups_are_retained(self):
        audit = json.loads((checker.REPO / 'docs/sage-remaining-clause-review.json').read_text())
        ledger = json.loads((checker.REPO / 'docs/sage-resolution-gaps.json').read_text())
        frozen = json.loads((checker.REPO / 'docs/sage-resolution-batch-review.json').read_text())
        for change in [lambda a: a['clauses'].pop(), lambda a: a['clauses'][0].update(text_sha256='wrong'), lambda a: a['clauses'][0].update(reason=''), lambda a: a.update(anchor_inspector_revision='wrong')]:
            with tempfile.TemporaryDirectory() as temporary:
                repo = Path(temporary)
                (repo / 'docs').mkdir()
                changed = copy.deepcopy(audit)
                change(changed)
                for name, content in [('sage-remaining-clause-review.json', changed), ('sage-resolution-gaps.json', ledger), ('sage-resolution-batch-review.json', frozen)]:
                    (repo / 'docs' / name).write_text(json.dumps(content))
                with self.assertRaises(AssertionError):
                    checker.verify_review(self.report, repo)


if __name__ == '__main__':
    unittest.main()
