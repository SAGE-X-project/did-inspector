// Package sageresolution observes SAGE record-backed resolution interfaces
// against pinned DID publications. It imports no subject implementation.
package sageresolution

import (
	"context"
	"encoding/json"
	"github.com/sage-x-project/did-inspector/core"
	"github.com/sage-x-project/did-inspector/profiles/sageprojection"
)

// Request names a native operation or an inspector-built loopback TLS request.
// SourceFailure is an explicit fixture failure, never operational evidence.
type Request struct {
	Function       string            `json:"function"`
	Input          string            `json:"input"`
	Accept         string            `json:"accept,omitempty"`
	Relationship   string            `json:"relationship,omitempty"`
	NativeFunction string            `json:"native_function,omitempty"`
	SourceFailure  string            `json:"source_failure,omitempty"`
	Options        map[string]any    `json:"options,omitempty"`
	HTTP           *core.HTTPRequest `json:"http,omitempty"`
}

// NativeObservation archives the actual native input and returned data compared
// with an HTTP exchange; it is not an expected result generated by the subject.
type NativeObservation struct {
	Request Request `json:"request"`
	Result  *Result `json:"result"`
}

// Result preserves native metadata, accessor snapshots and representation bytes,
// or a complete wire exchange. Native carries a separate actual function call.
type Result struct {
	Native          *NativeObservation `json:"native,omitempty"`
	Metadata        json.RawMessage    `json:"metadata"`
	ContentMetadata json.RawMessage    `json:"content_metadata"`
	HasContent      bool               `json:"has_content"`
	ReturnedID      string             `json:"returned_id,omitempty"`
	ContentKind     string             `json:"content_kind,omitempty"`
	Snapshot        json.RawMessage    `json:"snapshot,omitempty"`
	Raw             []byte             `json:"raw,omitempty"`
	SageCode        string             `json:"sage_code,omitempty"`
	Exchange        *core.HTTPExchange `json:"exchange,omitempty"`
}

// Subject does not imply generic fixture-method or deployment capabilities.
type Subject interface {
	core.Subject
	InspectResolution(context.Context, sageprojection.Record, Request) (Result, error)
}

// SerializedMetadata preserves a direct subject serializer call, including
// failures. Bytes are not RawMessage: malformed output must remain archivable.
type SerializedMetadata struct {
	Serializer string `json:"serializer"`
	Bytes      []byte `json:"bytes"`
	Error      string `json:"error,omitempty"`
}

// MetadataResult keeps resolution/dereferencing metadata and document or
// dereferenced-content metadata, with their independent
// serialization outcomes. It carries no subject validation verdict.
type MetadataResult struct {
	Resolution SerializedMetadata `json:"resolution"`
	Document   SerializedMetadata `json:"document"`
	SageCode   string             `json:"sage_code,omitempty"`
}

// MetadataSubject exposes fresh native 1.1 output serialization, independently
// of adapter JSON capture, HTTP bindings and legacy compatibility functions.
type MetadataSubject interface {
	core.Subject
	InspectMetadata(context.Context, sageprojection.Record, Request) (MetadataResult, error)
}

// ProductionCapture archives the actual pre-call maps and unchanged delegated
// return values. Byte fields preserve even malformed captures without repairs.
type ProductionCapture struct {
	Operation     string `json:"operation"`
	Model         []byte `json:"model"`
	Entries       []byte `json:"entries"`
	Version       string `json:"version"`
	JSONLD        bool   `json:"json_ld"`
	IncludeSecret bool   `json:"include_secret"`
	Output        []byte `json:"output"`
	MediaType     string `json:"media_type"`
	Error         string `json:"error,omitempty"`
	CaptureError  string `json:"capture_error,omitempty"`
}

// ConsumptionCapture separates actual wire input, detected information and
// the two returned accessor maps. No validation findings are used as an oracle.
type ConsumptionCapture struct {
	Operation    string   `json:"operation"`
	Input        []byte   `json:"input"`
	MediaType    string   `json:"media_type"`
	Require      string   `json:"require"`
	Expected     string   `json:"expected"`
	Strict       bool     `json:"strict"`
	Version      string   `json:"version"`
	JSONLD       bool     `json:"json_ld"`
	DroppedTerms []string `json:"dropped_terms"`
	Model        []byte   `json:"model"`
	Entries      []byte   `json:"entries"`
	Error        string   `json:"error,omitempty"`
	CaptureError string   `json:"capture_error,omitempty"`
}

// PipelineResult retains every call in one fresh native resolver execution.
// An absent, repeated or differently attributed call is not replaced by a
// generic producer/consumer test or a post-consumption getter snapshot.
type PipelineResult struct {
	Producer []ProductionCapture  `json:"producer"`
	Consumer []ConsumptionCapture `json:"consumer"`
	Result   Result               `json:"result"`
}

type PipelineSubject interface {
	core.Subject
	InspectPipeline(context.Context, sageprojection.Record, Request) (PipelineResult, error)
}

// ConsumptionRequest supplies literal public-document bytes and their declared
// representation to the same pinned consumer selected by SAGE integration.
type ConsumptionRequest struct {
	Data      []byte `json:"data"`
	MediaType string `json:"media_type"`
}

// ConsumptionSubject observes the selected library actor directly, not SAGE's
// resolver ingress. Its Go error means the adapter could not make the call;
// the actual consumer error remains inside ConsumptionCapture.
type ConsumptionSubject interface {
	core.Subject
	InspectConsumption(context.Context, ConsumptionRequest) (ConsumptionCapture, error)
}

// TypedValue preserves an actual model type, separately from its JSON encoding.
// Text carries strings, decimal numbers or full original datetime precision.
type TypedValue struct {
	Kind    string        `json:"kind"`
	Text    string        `json:"text,omitempty"`
	Flag    bool          `json:"flag,omitempty"`
	Items   []TypedValue  `json:"items,omitempty"`
	Members []TypedMember `json:"members,omitempty"`
}
type TypedMember struct {
	Name  string     `json:"name"`
	Value TypedValue `json:"value"`
}
type TypedProductionRequest struct {
	ControllerShape string        `json:"controller_shape,omitempty"`
	Version         string        `json:"version,omitempty"`
	ID              string        `json:"id"`
	Controllers     []string      `json:"controllers"`
	Fields          []TypedMember `json:"fields"`
	Entries         []TypedMember `json:"entries"`
	JSONLD          bool          `json:"json_ld"`
}

// TypedProductionResult witnesses the actual model before the delegated call.
// It cannot be replaced with a post-consumption snapshot or input JSON parser.
type TypedProductionResult struct {
	ID              string              `json:"id"`
	Controllers     []string            `json:"controllers"`
	ControllerShape string              `json:"controller_shape"`
	Fields          []TypedMember       `json:"fields"`
	Entries         []TypedMember       `json:"entries"`
	Calls           []ProductionCapture `json:"calls"`
	BuildError      string              `json:"build_error,omitempty"`
	CaptureError    string              `json:"capture_error,omitempty"`
}
type TypedProductionSubject interface {
	core.Subject
	InspectTypedProduction(context.Context, TypedProductionRequest) (TypedProductionResult, error)
}

// ConsumedMethod witnesses known datetime entries through actual typed accessors.
type ConsumedMethod struct {
	ID      string      `json:"id"`
	Expires *TypedValue `json:"expires,omitempty"`
	Revoked *TypedValue `json:"revoked,omitempty"`
}
type TypedConsumptionResult struct {
	Call            ConsumptionCapture `json:"call"`
	ID              string             `json:"id"`
	Controllers     []string           `json:"controllers"`
	ControllerShape string             `json:"controller_shape"`
	Fields          []TypedMember      `json:"fields"`
	Entries         []TypedMember      `json:"entries"`
	Methods         []ConsumedMethod   `json:"methods"`
	CaptureError    string             `json:"capture_error,omitempty"`
}
type TypedConsumptionSubject interface {
	core.Subject
	InspectTypedConsumption(context.Context, ConsumptionRequest) (TypedConsumptionResult, error)
}
